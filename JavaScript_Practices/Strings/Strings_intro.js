// In javascript, strings are used to represent text.
//  A string is a sequence of characters enclosed in single quotes (' '),
//  double quotes (" "), or backticks (` `).
//  Strings can contain letters, numbers, symbols, and whitespace.

// Example of strings:
let singleQuoteString = 'Hello, World!';
let doubleQuoteString = "Hello, World!";
let backtickString = `Hello, World!`;

// Strings can be concatenated using the + operator:
let greeting = 'Hello';
let name = 'Alice';
let message = greeting + ', ' + name + '!'; // "Hello, Alice!"

//printing the message
console.log(message); // Output: "Hello, Alice!"

